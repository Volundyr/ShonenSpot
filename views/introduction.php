            </p>
          </details>
          <details>
            <summary class="uk-active uk-text-center">Mecha</summary>
            <p class="uk-font uk-text-center">
            Un animé mecha met en scène des robots géants pilotés par des humains. Ces animés combinent souvent science-fiction, batailles épiques et dilemmes moraux liés à la technologie et à la guerre. Des titres célèbres incluent Gundam et Evangelion.
            </p>
          </details>
          <details>
            <summary class="uk-active uk-text-center">Isekai</summary>
            <p class="uk-font uk-text-center">
            Un animé isekai raconte l’aventure d’un ou plusieurs personnages transportés dans un autre monde, souvent fantastique ou médiéval. Ces histoires explorent la découverte de ce nouvel univers, la quête de pouvoir ou la survie, avec des thèmes d’évasion et de renaissance. Des exemples récents sont Sword Art Online et Re:Zero.
            </p>
          </details>
          <details>
            <summary class="uk-active uk-text-center">Slice</summary>
            <p class="uk-font uk-text-center">
            Un animé slice of life dépeint des moments du quotidien, souvent avec réalisme et simplicité. Il s’attache à montrer la beauté des petites choses, les relations humaines et les émotions ordinaires, parfois avec une touche de nostalgie. Clannad ou Barakamon illustrent bien ce genre.
            </p>
          </details>
          <details>
            <summary class="uk-active uk-text-center">Fantasy</summary>
            <p class="uk-font uk-text-center">
            Un animé fantasy se déroule dans des mondes imaginaires peuplés de créatures surnaturelles, de magie et d’aventures épiques. Ces animés explorent souvent la lutte entre le bien et le mal, avec des univers riches et détaillés. Made in Abyss et Fullmetal Alchemist sont des exemples marquants.
            </p>
